    /**
     * Updates the steplist textField with values from the machineBuilder.
     *
     * @author Linus Schoendorf, Marvin Jolk
     */
    private void setStepList() {
        DefaultListModel dfl = new DefaultListModel();

        List<State> stepList = machineBuilder.getCurrentSaves();
        String output;
        int stepCounter = 0;
        for (int i = 0; i < stepList.size(); i++) {
            output = "Step " + (stepCounter++ + 1) + ": " + stepList.get(i).toOutputString() + System.lineSeparator() + System.lineSeparator();
            dfl.addElement(output);
        }
        jList_SimulationSteps.setModel(dfl);
        jList_SimulationSteps.ensureIndexIsVisible(jList_SimulationSteps.getModel().getSize());
    }

