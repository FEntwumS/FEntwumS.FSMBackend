    /**
     * Does the setup which is needed to start the simulation.
     *
     * @return success report
     * @author Linus Schoendorf, Marvin Jolk
     */
    public boolean setup() {
        if (!machineBuilder.setupSimulation()) {
            logHandler.addError("Simulation cannot be set up");
            return false;
        }
        Simulator simulator = machineBuilder.getSimulator();
        //Set columns of output table
        tableModel = new DefaultTableModel();
        jTableOutputVector.setModel(tableModel);
        rowIndices = new HashMap<>();
        ArrayList<Signal> outputSignals = simulator.getAutomaton().getOutputSignals();
        tableModel.addColumn("State");
        for (int i = 0; i < outputSignals.size(); i++) {
            String signalName = outputSignals.get(i).getName();
            tableModel.addColumn(signalName);
        }
        //Set rows of output table
        ArrayList<State> states = simulator.getAutomaton().getStates();
        for (int i = 0; i < states.size(); i++) {
            State state = states.get(i);
            rowIndices.put(state.getName(), i);
            Hashtable outputVector = state.getOutputVector();
            Vector vector = new Vector();
            vector.add(state.getName());
            for (Signal signal : outputSignals) {
                vector.add(outputVector.get(signal));
            }
            tableModel.addRow(vector);
        }
        updateHighlightedRow();
        updateInputVectorTable(true, 0);

        //set variables
        updateVariables();
        return true;
    }

    /**
     * Updates the input vector table. Among other things required after an
     * added or removed vector.
     *
     * @param reset
     * @param increment
     * @author Linus Schoendorf, Marvin Jolk
     */
    private void updateInputVectorTable(boolean reset, int increment) {
        //Set column names of input vector table
        inputVectorColumnIndices = new HashMap<>();
        tableModelInput = new DefaultTableModel();
        SignalVectorList inputVector = machineBuilder.getInputVectors();
        ArrayList<Hashtable<String, Integer>> inputHashtable = inputVector.getSignalsVectorList();

        ArrayList<Signal> inputSignals = machineBuilder.getSimulator().getAutomaton().getInputSignals();
        for (int i = 0; i < inputSignals.size(); i++) {
            String s = inputSignals.get(i).getName();
            tableModelInput.addColumn(s);
            inputVectorColumnIndices.put(s, i);
        }
        //Set rows of input vector table
        for (int i = 0; i < inputHashtable.size(); i++) {
            Hashtable<String, Integer> h = inputHashtable.get(i);
            Vector vectorInput = new Vector();
            for (Signal signal : inputSignals) {
                vectorInput.add(h.get(signal.getName()));
            }
            tableModelInput.addRow(vectorInput);
        }
        jTableInputVectors.setModel(tableModelInput);
        setTableChangedListener();
        highlightNextInputVector(reset, increment);
    }

    /**
     * Updates the variables.
     *
     * @author Linus Schoendorf, Marvin Jolk
     */
    private void updateVariables() {
        //set variables
        tableModelVariables = new DefaultTableModel();
        tableModelVariables.addColumn("Name");
        tableModelVariables.addColumn("Value");
        jTableVariables.setModel(tableModelVariables);
        ArrayList<Variable> variables = machineBuilder.getSimulator().getAutomaton().getVariables();
        for (Variable v : variables) {
            Vector vector = new Vector();
            vector.add(v.getName());
            vector.add(v.getValue());
            tableModelVariables.addRow(vector);
        }
    }

