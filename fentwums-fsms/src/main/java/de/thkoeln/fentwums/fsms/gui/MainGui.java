    /**
     * Adds a vector to the vector list on the selected position. If nothing is
     * selected it adds it in the end.
     *
     * @param evt Activation of the button
     * @author Linus Schoendorf, Marvin Jolk
     */
    private void jButtonAddVectorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddVectorActionPerformed

        SignalVectorList s = machineBuilder.getInputVectors();
        int index = jTableInputVectors.getSelectedRow() + 1;
        if (index <= 0) {
            index = s.getSignalsVectorList().size();
        }
        if (!s.addVectorAt(index)) {
            return;
        }
        machineBuilder.setInputVectors(s);
        if (index < rendererInputTable.getHighlightedRow()) {
            updateInputVectorTable(false, 1);
        } else {
            updateInputVectorTable(false, 0);
        }
    }//GEN-LAST:event_jButtonAddVectorActionPerformed

